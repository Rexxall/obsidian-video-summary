#!/usr/bin/env node
// Build the Ithaca notebook style for video notes into styles.css, between the two markers.
// Every rule is put behind body.vs-notebook-style, which the setting switches on, so the style
// costs nothing when it is off.  node tools/build-notebook-style.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';
import prettier from 'prettier';

const ROOT = new URL('../', import.meta.url);
const SOURCES = ['styles/notebook/film.css', 'styles/notebook/pieces.css'];
const START = '/* ---- Ithaca notebook style (generated by tools/build-notebook-style.mjs) ---- */';
const END = '/* ---- end of Ithaca notebook style ---- */';
const GATE = '.vs-notebook-style';

export function gateSelector(selector) {
  const s = selector.trim();
  if (/^body\b/.test(s)) return s.replace(/^body/, `body${GATE}`);
  if (/^\.theme-(dark|light)\b/.test(s)) return `body${GATE}${s}`;
  return `body${GATE} ${s}`;
}

function build() {
  const parts = SOURCES.map((path) => {
    const root = postcss.parse(readFileSync(new URL(path, ROOT), 'utf8'));
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
      rule.selectors = rule.selectors.map(gateSelector);
    });
    root.walkComments((comment) => comment.remove());
    return root.toString().trim();
  });
  return `${START}\n${parts.join('\n\n')}\n${END}`;
}

const stylesUrl = new URL('styles.css', ROOT);
const styles = readFileSync(stylesUrl, 'utf8');
const block = build();
const start = styles.indexOf(START);
const end = styles.indexOf(END);
const joined =
  start >= 0 && end > start
    ? styles.slice(0, start) + block + styles.slice(end + END.length)
    : `${styles.trimEnd()}\n\n${block}\n`;
// Formatted as the repository formats CSS, so `prettier --check` and this build agree.
const next = await prettier.format(joined, {
  ...(await prettier.resolveConfig(stylesUrl.pathname)),
  filepath: stylesUrl.pathname,
});
if (process.argv.includes('--check')) {
  if (next !== styles) {
    process.stderr.write('styles.css is out of date: run node tools/build-notebook-style.mjs\n');
    process.exit(1);
  }
} else {
  writeFileSync(stylesUrl, next);
}
