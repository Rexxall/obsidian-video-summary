import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const options = {
  banner: { js: banner },
  entryPoints: ['main.ts'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
  ],
  format: 'cjs',
  target: 'es2020',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: 'main.js',
};

async function run() {
  try {
    if (prod) {
      await esbuild.build(options);
    } else {
      // 兼容老版本 esbuild（无 context/watch）
      if (typeof esbuild.context === 'function') {
        const ctx = await esbuild.context(options);
        await ctx.watch();
        process.stdout.write('esbuild watching...\n');
      } else {
        await esbuild.build({ ...options, watch: true });
        process.stdout.write('esbuild watching (legacy)...\n');
      }
    }
  } catch (_) {
    process.exit(1);
  }
}

run();
